# 6. Model (linear CTC head), greedy decode, WER
class CTCHead(nn.Module):
    def __init__(self, dim=HID, vocab_size=VOCAB_SIZE, p_drop=0.1):
        super().__init__()
        self.dropout = nn.Dropout(p_drop)
        self.fc = nn.Linear(dim, vocab_size)

    def forward(self, x):                 # [B,T,768] -> [B,T,V]
        return self.fc(self.dropout(x))


def greedy_decode(ids):
    out, prev = [], -1
    for t in ids:
        if t != prev and t != BLANK_ID:
            out.append(ID2CH.get(t, ""))
        prev = t
    return "".join(out).replace("|", " ").strip()


@torch.no_grad()
def evaluate_wer(model, dl, ds):
    model.eval()
    hyps, refs = [], []
    for x, y, xlen, ylen, idxs in dl:
        logits = model(x.to(DEVICE))
        pred = logits.argmax(-1).cpu().numpy()
        for b, i in enumerate(idxs):
            hyps.append(greedy_decode(pred[b, :xlen[b]].tolist()))
            refs.append(ds.texts[i])
    return jiwer.wer(refs, hyps), hyps, refs

# 7. STAGE B - training loop
model = CTCHead().to(DEVICE)
n_par = sum(p.numel() for p in model.parameters())
print(f"[MODEL] trainable params: {n_par:,} (CTC head only)")

optimizer = torch.optim.AdamW(model.parameters(), lr=LR)
scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
    optimizer, mode="min", factor=LR_FACTOR, patience=LR_PATIENCE)
ctc = nn.CTCLoss(blank=BLANK_ID, reduction="mean", zero_infinity=True)

os.makedirs(OUTPUT_DIR, exist_ok=True)
best_wer, best_epoch = float("inf"), -1

for epoch in range(1, NUM_EPOCHS + 1):
    model.train()
    t0, tot_loss, n_batches = time.perf_counter(), 0.0, 0
    for x, y, xlen, ylen, _ in train_dl:
        x, y = x.to(DEVICE, non_blocking=True), y.to(DEVICE)
        logits = model(x)
        logp = logits.log_softmax(-1).transpose(0, 1)      # [T,B,V]
        loss = ctc(logp, y, xlen.to(DEVICE), ylen.to(DEVICE))
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
        tot_loss += loss.item(); n_batches += 1

    wer, hyps, refs = evaluate_wer(model, dev_dl, dev_ds)
    scheduler.step(wer)
    lr_now = optimizer.param_groups[0]["lr"]
    print(f"[TRAIN] epoch {epoch:>2} | loss {tot_loss/max(n_batches,1):.4f} | "
          f"dev-WER {wer*100:.2f}% | lr {lr_now:.2e} | "
          f"{time.perf_counter()-t0:.1f} s")

    if wer < best_wer:
        best_wer, best_epoch = wer, epoch
        torch.save(model.state_dict(), os.path.join(OUTPUT_DIR, "ctc_head_best.pt"))
    elif epoch - best_epoch >= STOP_PATIENCE:
        print(f"[TRAIN] early stop (no improvement for {STOP_PATIENCE} epochs)")
        break

tokenizer.save_pretrained(OUTPUT_DIR)
feature_extractor.save_pretrained(OUTPUT_DIR)
print(f"\n[TRAIN] best dev-WER: {best_wer*100:.2f}% (epoch {best_epoch})")
print(f"[TRAIN] head + tokenizer + feature_extractor -> {OUTPUT_DIR}")
print("[TRAIN] sample output:")
for h, r in zip(hyps[:3], refs[:3]):
    print(f"  REF: {r}\n  HYP: {h}")

