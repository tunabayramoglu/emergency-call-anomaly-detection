"""### Notes

- **Stage A is a one-off cost.** On an L4 with 24 GB the fp16 forward runs at roughly 100-200x real time, so 100 hours of audio takes about 40-60 minutes. If it is interrupted, Run All again is safe because a completed cache is skipped.
- **Stage B is very cheap.** For a 23K-parameter head an epoch takes seconds to tens of seconds, and all 30 epochs take minutes. The bottleneck is now the memmap disk read, and with 40 GB of RAM the OS page cache holds most of the train cache, so it speeds up from the second epoch on.
- **The inference chain:** audio -> feature_extractor -> mHuBERT (fp16, frozen) -> `ctc_head_best.pt` -> greedy decode. The forward inside `flush` in Stage A plus `greedy_decode` in cell 6 are exactly this chain.
- **Smoke test:** `MAX_TRAIN_SAMPLES=512` and `MAX_EVAL_SAMPLES=256` run end to end in about 5 minutes. Then delete the cache folder (`!rm -rf feat_cache`) and switch to the real run with `None`.
- A WER below 10% with a purely linear head is an aggressive target. If convergence stalls, adding one hidden layer to `CTCHead` (768->768 GELU->30) gives a clear gain for a small departure from the roadmap.
"""

# === LAYER SWEEP: which mHuBERT layer gives the best linear probe? ===
SWEEP_DIR    = "./sweep_cache"
SWEEP_LAYERS = [3, 5, 7, 9, 11, 12]   # hidden_states index (0=embedding, 12=last layer)
N_TRAIN_SW   = 768
N_DEV_SW     = 256
EPOCHS_SW    = 10
BATCH_SW     = 128
LR_SW        = 2e-3

os.makedirs(SWEEP_DIR, exist_ok=True)

def sweep_precompute(backbone, split, n, prefix):
    files = {L: open(os.path.join(SWEEP_DIR, f"{prefix}_L{L}.f16"), "wb")
             for L in SWEEP_LAYERS}
    lengths, labels, texts = [], [], []
    stream = load_dataset(DATASET_ID, "clean", split=split, streaming=True)
    stream = stream.cast_column("audio", Audio(sampling_rate=SR))

    def flush(buf_a, buf_t):
        enc = feature_extractor(buf_a, sampling_rate=SR, padding=True,
                                return_tensors="pt", return_attention_mask=True)
        iv = enc.input_values.to(DEVICE, dtype=torch.float16)
        am = enc.attention_mask.to(DEVICE)
        with torch.no_grad():
            hs = backbone(iv, attention_mask=am,
                          output_hidden_states=True).hidden_states
        valid = backbone._get_feat_extract_output_lengths(am.sum(-1)).tolist()
        for L in SWEEP_LAYERS:
            h = hs[L].cpu().numpy()
            for i, T in enumerate(valid):
                h[i, :T].astype(np.float16).tofile(files[L])
        for T, txt in zip(valid, buf_t):
            lengths.append(int(T))
            labels.append(tokenizer(txt.upper()).input_ids)
            texts.append(txt.upper())

    buf_a, buf_t = [], []
    for ex in itertools.islice(stream, n):
        buf_a.append(ex["audio"]["array"].astype(np.float32))
        buf_t.append(ex["text"])
        if len(buf_a) == PRECOMPUTE_BATCH:
            flush(buf_a, buf_t); buf_a, buf_t = [], []
    if buf_a:
        flush(buf_a, buf_t)
    for f in files.values():
        f.close()
    print(f"[SWEEP] {prefix}: {len(lengths)} samples, {len(SWEEP_LAYERS)} layers")
    return {"lengths": lengths, "labels": labels, "texts": texts}


class SweepDS(Dataset):
    def __init__(self, path, meta):
        self.lengths, self.labels, self.texts = \
            meta["lengths"], meta["labels"], meta["texts"]
        self.offsets = np.concatenate([[0], np.cumsum(self.lengths)])[:-1]
        self.mm = np.memmap(path, dtype=np.float16, mode="r").reshape(-1, HID)
    def __len__(self): return len(self.lengths)
    def __getitem__(self, i):
        o, L = int(self.offsets[i]), self.lengths[i]
        x = torch.from_numpy(np.array(self.mm[o:o+L], dtype=np.float32))
        return x, torch.tensor(self.labels[i], dtype=torch.long), L, i


print("[SWEEP] loading the backbone...")
bb = HubertModel.from_pretrained(BACKBONE_ID, torch_dtype=torch.float16).to(DEVICE).eval()
tr_meta = sweep_precompute(bb, "train.100", N_TRAIN_SW, "tr")
dv_meta = sweep_precompute(bb, "validation", N_DEV_SW, "dv")
del bb
if DEVICE == "cuda": torch.cuda.empty_cache()

ctc_sw = nn.CTCLoss(blank=BLANK_ID, reduction="mean", zero_infinity=True)
results = []
for L in SWEEP_LAYERS:
    tr_ds = SweepDS(os.path.join(SWEEP_DIR, f"tr_L{L}.f16"), tr_meta)
    dv_ds = SweepDS(os.path.join(SWEEP_DIR, f"dv_L{L}.f16"), dv_meta)
    tr_dl = DataLoader(tr_ds, batch_sampler=BucketBatchSampler(tr_ds.lengths, BATCH_SW),
                       collate_fn=collate, num_workers=0)
    dv_dl = DataLoader(dv_ds, batch_sampler=BucketBatchSampler(dv_ds.lengths, BATCH_SW, shuffle=False),
                       collate_fn=collate, num_workers=0)
    probe = CTCHead().to(DEVICE)
    opt = torch.optim.AdamW(probe.parameters(), lr=LR_SW)
    for ep in range(EPOCHS_SW):
        probe.train()
        for x, y, xl, yl, _ in tr_dl:
            logp = probe(x.to(DEVICE)).log_softmax(-1).transpose(0, 1)
            loss = ctc_sw(logp, y.to(DEVICE), xl.to(DEVICE), yl.to(DEVICE))
            opt.zero_grad(set_to_none=True); loss.backward(); opt.step()
    # dev loss + dev WER
    probe.eval(); dl_sum, nb = 0.0, 0
    with torch.no_grad():
        for x, y, xl, yl, _ in dv_dl:
            logp = probe(x.to(DEVICE)).log_softmax(-1).transpose(0, 1)
            dl_sum += ctc_sw(logp, y.to(DEVICE), xl.to(DEVICE), yl.to(DEVICE)).item(); nb += 1
    wer, _, _ = evaluate_wer(probe, dv_dl, dv_ds)
    results.append((L, dl_sum / nb, wer))
    print(f"[SWEEP] layer {L:>2} | dev-loss {dl_sum/nb:.3f} | dev-WER {wer*100:6.2f}%")

print("\n[SWEEP] ===== RANKING (by dev loss) =====")
for L, dl_, w in sorted(results, key=lambda r: r[1]):
    print(f"  layer {L:>2}: dev-loss {dl_:.3f} | dev-WER {w*100:6.2f}%")