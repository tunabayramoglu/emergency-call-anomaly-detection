def cell(source_lines, cell_type="code"):
    src = [s + "\n" if not s.endswith("\n") else s for s in source_lines]
    return {"cell_type": cell_type, "metadata": {}, "source": src}

def md(header, body=""):
    lines = [header]
    if body:
        lines.append("")
        lines.append(body)
    return cell(lines, "markdown")

